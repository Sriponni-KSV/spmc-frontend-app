  String translate(String key, {String? fallback, Map<String, String>? params}) {
    final langCode = locale.languageCode;
    String result;
    if (_localizedValues.containsKey(langCode) &&
        _localizedValues[langCode]!.containsKey(key)) {
      result = _localizedValues[langCode]![key]!;
    } else if (_localizedValues['en']!.containsKey(key)) {
      result = _localizedValues['en']![key]!;
    } else {
      result = fallback ?? key;
    }
    if (params != null && params.isNotEmpty) {
      params.forEach((paramKey, value) {
        result = result.replaceAll('{$paramKey}', value);
      });
    }
    return result;
  }

  String translateMedicine(String name) {
    if (locale.languageCode != 'ta') return name;
    final key = name.trim().toLowerCase();
    if (_medicineTamilMap.containsKey(key)) {
      return _medicineTamilMap[key]!;
    }
    for (var entry in _medicineTamilMap.entries) {
      if (key == entry.key || key.startsWith(entry.key)) {
        return entry.value;
      }
    }
    return name;
  }

