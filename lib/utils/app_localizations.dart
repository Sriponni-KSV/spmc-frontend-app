class _AppLocalizationsDelegate
    extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => ['en', 'ta'].contains(locale.languageCode);

  @override
  Future<AppLocalizations> load(Locale locale) {
    return SynchronousFuture<AppLocalizations>(AppLocalizations(locale));
  }

  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;
}

extension AppLocalizationExtension on BuildContext {
  String tr(String key, {String? fallback, Map<String, String>? params}) {
    return AppLocalizations.of(this).translate(key, fallback: fallback, params: params);
  }

  String translateMedicine(String name) {
    return AppLocalizations.of(this).translateMedicine(name);
  }

  String translateProcedure(String name) {
    return AppLocalizations.of(this).translateProcedure(name);
  }

  String translateConsumable(String name) {
    return AppLocalizations.of(this).translateConsumable(name);
  }

  String translateRole(String role) {
    switch (role.trim().toLowerCase()) {
      case 'nurse':
        return tr('nurse', fallback: 'Nurse');
      case 'doctor':
        return tr('doctor', fallback: 'Doctor');
      case 'admin':
      case 'administrator':
        return tr('admin', fallback: 'Administrator');
      case 'super admin':
      case 'super_admin':
        return tr('super_admin', fallback: 'Super Administrator');
      case 'front desk':
      case 'receptionist':
        return tr('front_desk', fallback: 'Front Desk');
      case 'lab technician':
      case 'lab_technician':
        return tr('lab_technician', fallback: 'Lab Technician');
      case 'pharmacist':
        return tr('pharmacist', fallback: 'Pharmacist');
      case 'anaesthetist':
        return tr('anaesthetist', fallback: 'Anaesthetist');
      default:
        return role;
    }
  }
}
